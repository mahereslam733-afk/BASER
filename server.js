const express = require("express");
const path = require("path");

const app = express();

const PORT = process.env.PORT || 3000;

app.use(express.json({
    limit: "20mb"
}));

app.use(express.static(__dirname));


// ======================================================
// BASER - بصير
// Gemini Vision
// وصف المشهد الحقيقي + قراءة النصوص
// ======================================================

app.post("/api/vision", async (req, res) => {

    try {

        const image = req.body.image;
        const task = req.body.task;

        // ------------------------------------------
        // التأكد من وجود الصورة
        // ------------------------------------------

        if (!image) {

            return res.status(400).json({
                success: false,
                error: "لم يتم إرسال صورة"
            });

        }


        // ------------------------------------------
        // التأكد من وجود مفتاح Gemini
        // ------------------------------------------

        if (!process.env.GEMINI_API_KEY) {

            console.error(
                "GEMINI_API_KEY غير موجود"
            );

            return res.status(500).json({
                success: false,
                error: "مفتاح Gemini غير موجود على الخادم"
            });

        }


        // ------------------------------------------
        // تحديد نوع المهمة
        // ------------------------------------------

        let instruction = "";


        // ==================================================
        // وصف المشهد
        // ==================================================

        if (task === "scene") {

            instruction = `
أنت نظام رؤية حاسوبي اسمه "بصير"،
ومهمتك مساعدة شخص كفيف على فهم الصورة أمامه.

حلل الصورة المرفقة نفسها فقط.

قواعد مهمة جدًا:

- لا تخترع أي شيء.
- لا تتوقع أو تتخيل محتوى الصورة.
- لا تذكر أي شيء غير ظاهر في الصورة.
- لا تستخدم معلومات من صور سابقة.
- لا تستخدم أمثلة جاهزة كوصف للصورة.
- لا تفترض أن الصورة تحتوي على غرفة أو شارع أو مكتب أو منزل.
- لا تذكر شخصًا إلا إذا كان ظاهرًا فعلًا.
- لا تذكر سيارة إلا إذا كانت ظاهرة فعلًا.
- لا تذكر طاولة أو كرسي أو باب أو أي شيء آخر إلا إذا كان ظاهرًا فعلًا.
- إذا كان العنصر غير واضح، لا تخمنه.
- إذا كانت الصورة غير واضحة بدرجة تمنع وصفها، قل:
"الصورة غير واضحة بما يكفي لوصف المشهد."

صف فقط ما يمكنك رؤيته بثقة.

ابدأ بالوصف العام للمشهد إذا كان واضحًا.

ثم اذكر أهم العناصر الموجودة فعلًا.

إذا كان هناك أشخاص، اذكر عددهم ومكانهم التقريبي وما يفعلونه فقط إذا كان ذلك واضحًا.

إذا كانت هناك أشياء مهمة، اذكرها.

إذا كان هناك نص واضح داخل الصورة، يمكنك ذكر وجوده، ولكن لا تقرأ النص كاملًا هنا.

استخدم لغة عربية بسيطة ومباشرة ومناسبة لشخص كفيف.

اجعل الوصف مختصرًا وواضحًا.

لا تستخدم عبارات تخمينية مثل:
"ربما"
"من المحتمل"
"يبدو أنه"
إلا إذا كان من الضروري توضيح عدم اليقين.

إذا لم تكن متأكدًا من وجود عنصر، لا تذكره.

الصورة الحالية هي المصدر الوحيد للمعلومات.
`;


        // ==================================================
        // قراءة النصوص
        // ==================================================

        } else if (task === "text") {

            instruction = `
أنت نظام قراءة نصوص بصري لتطبيق "بصير".

اقرأ النص الموجود في الصورة المرفقة فقط.

القواعد:

- لا تخترع أي نص.
- لا تضف كلمات غير موجودة.
- لا تفسر النص.
- لا تلخص النص.
- حافظ على ترتيب النص قدر الإمكان.
- إذا كان النص باللغة العربية، اكتبه بالعربية.
- إذا كان باللغة الإنجليزية، اكتبه بالإنجليزية.
- إذا كانت كلمة غير واضحة، اكتب:
[غير واضح]
- إذا لم يوجد نص واضح، قل:
"لم أجد نصًا واضحًا في الصورة."

أخرج النص فقط بدون شرح إضافي.
`;


        // ==================================================
        // نوع مهمة غير معروف
        // ==================================================

        } else {

            return res.status(400).json({
                success: false,
                error: "نوع الطلب غير معروف"
            });

        }


        // ==================================================
        // استخراج Base64 من الصورة
        // ==================================================

        let base64Image = image;

        if (
            base64Image.includes(",")
        ) {

            base64Image =
                base64Image.split(",")[1];

        }


        // ==================================================
        // تحديد نوع الصورة
        // ==================================================

        let mimeType = "image/jpeg";

        if (
            image.startsWith("data:image/png")
        ) {

            mimeType = "image/png";

        } else if (
            image.startsWith("data:image/webp")
        ) {

            mimeType = "image/webp";

        } else if (
            image.startsWith("data:image/jpeg")
        ) {

            mimeType = "image/jpeg";

        }


        // ==================================================
        // الاتصال بـ Gemini
        // ==================================================

        const apiUrl =
            "https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=" +
            encodeURIComponent(
                process.env.GEMINI_API_KEY
            );


        const response =
            await fetch(
                apiUrl,
                {

                    method: "POST",

                    headers: {
                        "Content-Type":
                            "application/json"
                    },

                    body: JSON.stringify({

                        contents: [

                            {

                                role: "user",

                                parts: [

                                    {
                                        text:
                                            instruction
                                    },

                                    {

                                        inline_data: {

                                            mime_type:
                                                mimeType,

                                            data:
                                                base64Image

                                        }

                                    }

                                ]

                            }

                        ],

                        generationConfig: {

                            temperature: 0.1,

                            topP: 0.8,

                            maxOutputTokens: 500

                        }

                    })

                }
            );


        // ==================================================
        // قراءة رد Gemini
        // ==================================================

        const data =
            await response.json();


        if (!response.ok) {

            console.error(
                "Gemini API Error:",
                JSON.stringify(
                    data,
                    null,
                    2
                )
            );

            return res.status(500).json({

                success: false,

                error:
                    "حدث خطأ أثناء الاتصال بخدمة Gemini"

            });

        }


        // ==================================================
        // استخراج النص
        // ==================================================

        const result =
            data
                ?.candidates?.[0]
                ?.content
                ?.parts
                ?.map(
                    part =>
                        part.text || ""
                )
                .join("")
                .trim();


        // ==================================================
        // لا توجد نتيجة
        // ==================================================

        if (!result) {

            console.error(
                "Gemini لم يرجع وصفًا"
            );

            return res.status(500).json({

                success: false,

                error:
                    "لم يتم الحصول على وصف للصورة"

            });

        }


        // ==================================================
        // إرسال النتيجة للتطبيق
        // ==================================================

        return res.json({

            success: true,

            result: result

        });


    } catch (error) {

        console.error(
            "BASER SERVER ERROR:",
            error
        );

        return res.status(500).json({

            success: false,

            error:
                "حدث خطأ أثناء تحليل الصورة"

        });

    }

});


// ======================================================
// الصفحة الرئيسية
// ======================================================

app.get("/", (req, res) => {

    res.sendFile(
        path.join(
            __dirname,
            "index.html"
        )
    );

});


// ======================================================
// تشغيل السيرفر
// ======================================================

app.listen(
    PORT,
    () => {

        console.log(
            `BASER server running on port ${PORT}`
        );

    }
);
